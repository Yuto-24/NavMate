"""Setup remains usable without host Node and never targets the primary runtime."""

import hashlib
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[2] / "scripts/codex/setup_worktree.sh"


class WorktreeSetupTests(unittest.TestCase):
    def run_setup(self, *, host_node=False, cpus="8", existing=True, wsl=False):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            bin_dir = root / "bin"
            bin_dir.mkdir()
            for command in ("bash", "python3", "grep", "mkdir", "cat", "id"):
                (bin_dir / command).symlink_to(shutil.which(command))
            git = bin_dir / "git"
            git.write_text('#!/bin/sh\nprintf "%s\\n" "$PWD"\n')
            git.chmod(0o755)
            log = root / "commands"
            docker = bin_dir / "docker"
            docker.write_text(
                '#!/bin/sh\nprintf "%s\\n" "$*" >> "$TEST_LOG"\n'
                'if [ "$1" = info ]; then printf "%s\\n" "$TEST_CPUS"; fi\n'
            )
            docker.chmod(0o755)
            if host_node:
                for name in ("node", "npm"):
                    path = bin_dir / name
                    path.write_text('#!/bin/sh\nprintf "host %s\\n" "$*" >> "$TEST_LOG"\n')
                    path.chmod(0o755)
            env_file = root / ".env"
            content = (
                (
                    "# Generated by AutoNavLog Codex worktree setup\n"
                    "COMPOSE_PROJECT_NAME=autonavlog-wt-01234567\n"
                    "COMPOSE_FILE=compose.yaml:.autonavlog-worktree/compose.override.yaml\n"
                    "AUTONAVLOG_IMAGE=autonavlog:wt-01234567\n"
                    "AUTONAVLOG_HOST_PORT=24567\n"
                )
                if existing
                else "COMPOSE_PROJECT_NAME=autonavlog\n"
            )
            if wsl:
                content = content.replace("compose.yaml:", "compose.yaml:compose.wsl.yaml:")
            env_file.write_text(content)
            result = subprocess.run(
                ["bash", str(SCRIPT)],
                cwd=root,
                text=True,
                capture_output=True,
                env={**os.environ, "PATH": str(bin_dir), "TEST_LOG": str(log), "TEST_CPUS": cpus},
            )
            self.assertEqual(env_file.read_text(), content)
            override = root / ".autonavlog-worktree/compose.override.yaml"
            return result, log.read_text(), override.read_text() if override.exists() else ""

    def test_missing_node_uses_owned_docker_install_and_caps_cpu(self):
        result, log, override = self.run_setup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn(f"run --rm --user {os.getuid()}:{os.getgid()}", log)
        self.assertIn("node:22-bookworm-slim npm --prefix web ci", log)
        self.assertIn('cpus: "8"', override)
        self.assertIn('image: "autonavlog:wt-01234567"', override)

    def test_both_platforms_disable_background_work(self):
        for wsl in (False, True):
            result, _, override = self.run_setup(wsl=wsl)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn('restart: "no"', override)
            self.assertIn('AUTONAVLOG_MSM_PREWARM: "${AUTONAVLOG_MSM_PREWARM:-false}"', override)
            if wsl:
                self.assertIn("      - msm", override)

    def test_host_node_and_large_daemon_keep_existing_limits(self):
        result, log, override = self.run_setup(host_node=True, cpus="16")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("host --prefix web ci", log)
        self.assertNotIn("run --rm", log)
        self.assertIn('cpus: "10"', override)

    def test_invalid_cpu_capacity_stops_before_install(self):
        result, log, override = self.run_setup(cpus="0")
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn("run --rm", log)
        self.assertEqual(override, "")

    def test_user_env_is_never_overwritten(self):
        result, log, override = self.run_setup(existing=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("Refusing to overwrite", result.stderr)
        self.assertNotIn("run --rm", log)
        self.assertEqual(override, "")


class WorktreeCleanupTests(unittest.TestCase):
    def run_cleanup(self, *, available=True, fail_down=False, primary=False,
                    wrong_project=False, wrong_image=False, dirty=False, status_failure=False,
                    fail_image=False, image_present=True, image_inspection_failure=False,
                    env_symlink=None):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            bin_dir = root / "bin"
            bin_dir.mkdir()
            for command in ("bash", "python3", "grep", "rm"):
                (bin_dir / command).symlink_to(shutil.which(command))
            git = bin_dir / "git"
            git.write_text(
                '#!/bin/sh\n'
                'if [ "$1" = status ]; then\n'
                '  printf "%s" "$DIRTY_STATUS"; exit "$STATUS_EXIT"\n'
                'fi\nprintf "%s\\n" "$PWD"\n'
            )
            git.chmod(0o755)
            log = root / "commands"
            docker = bin_dir / "docker"
            docker.write_text(
                '#!/bin/sh\nprintf "%s\\n" "$*" >> "$TEST_LOG"\n'
                'if [ "$1" = info ]; then exit "$INFO_EXIT"; fi\n'
                'if [ "$1" = compose ]; then exit "$DOWN_EXIT"; fi\n'
                'if [ "$1 $2" = "image ls" ]; then\n'
                '  printf "%s" "$IMAGE_ID"; exit "$IMAGE_INSPECT_EXIT"\n'
                'fi\n'
                'if [ "$1 $2" = "image rm" ]; then exit "$IMAGE_EXIT"; fi\n'
            )
            docker.chmod(0o755)
            worktree_id = hashlib.sha256(str(root).encode()).hexdigest()[:8]
            project = "autonavlog-wt-" + ("01234567" if wrong_project else worktree_id)
            image = "autonavlog:wt-" + ("01234567" if wrong_image else worktree_id)
            (root / ".env").write_text(
                '# Generated by AutoNavLog Codex worktree setup\n'
                f'COMPOSE_PROJECT_NAME={"autonavlog" if primary else project}\n'
                f'AUTONAVLOG_IMAGE={image}\n'
                'COMPOSE_FILE=compose.yaml:.autonavlog-worktree/compose.override.yaml\n'
            )
            (root / ".autonavlog-worktree").mkdir()
            if env_symlink:
                (root / ".env").rename(root / "saved.env")
                (root / ".env").symlink_to(root / env_symlink)
            result = subprocess.run(
                ["bash", str(SCRIPT.with_name("cleanup_worktree.sh"))], cwd=root,
                text=True, capture_output=True,
                env={**os.environ, "PATH": str(bin_dir), "TEST_LOG": str(log),
                     "INFO_EXIT": "0" if available else "1",
                     "DOWN_EXIT": "1" if fail_down else "0",
                     "DIRTY_STATUS": "?? unfinished.txt\n" if dirty else "",
                     "STATUS_EXIT": "1" if status_failure else "0",
                     "IMAGE_ID": "sha256:test" if image_present else "",
                     "IMAGE_INSPECT_EXIT": "1" if image_inspection_failure else "0",
                     "IMAGE_EXIT": "1" if fail_image else "0"},
            )
            retained = ((root / ".env").exists() or (root / ".env").is_symlink()) and (
                root / ".autonavlog-worktree").is_dir()
            return result, retained, log.read_text() if log.exists() else ""

    def test_success_removes_generated_configuration(self):
        result, retained, log = self.run_cleanup()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(retained)
        self.assertIn("compose down -v --remove-orphans", log)

    def test_unavailable_docker_retains_retry_configuration(self):
        result, retained, log = self.run_cleanup(available=False)
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(retained)
        self.assertNotIn("compose down", log)

    def test_failed_cleanup_retains_retry_configuration(self):
        result, retained, log = self.run_cleanup(fail_down=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(retained)
        self.assertNotIn("image rm", log)

    def test_primary_project_is_rejected(self):
        result, retained, log = self.run_cleanup(primary=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(retained)
        self.assertEqual(log, "")

    def test_foreign_project_or_image_is_rejected_before_docker(self):
        for options in ({"wrong_project": True}, {"wrong_image": True},
                        {"wrong_project": True, "wrong_image": True}):
            result, retained, log = self.run_cleanup(**options)
            self.assertNotEqual(result.returncode, 0)
            self.assertTrue(retained)
            self.assertEqual(log, "")

    def test_unfinished_or_unknown_git_state_is_rejected_before_docker(self):
        for options in ({"dirty": True}, {"status_failure": True}):
            result, retained, log = self.run_cleanup(**options)
            self.assertNotEqual(result.returncode, 0)
            self.assertTrue(retained)
            self.assertEqual(log, "")

    def test_failed_image_removal_keeps_configuration_for_retry(self):
        result, retained, log = self.run_cleanup(fail_image=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(retained)
        self.assertIn("image rm autonavlog:wt-", log)
        self.assertNotIn("--force", log)

    def test_absent_image_allows_idempotent_cleanup(self):
        result, retained, log = self.run_cleanup(image_present=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(retained)
        self.assertNotIn("image rm", log)

    def test_unknown_image_state_retains_configuration(self):
        result, retained, log = self.run_cleanup(image_inspection_failure=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertTrue(retained)
        self.assertNotIn("image rm", log)

    def test_symlinked_env_is_rejected_even_when_its_target_is_missing(self):
        for target in ("saved.env", "missing.env"):
            result, retained, log = self.run_cleanup(env_symlink=target)
            self.assertNotEqual(result.returncode, 0)
            self.assertTrue(retained)
            self.assertEqual(log, "")
