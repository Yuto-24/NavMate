#!/usr/bin/env bash

set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

ENV_FILE="$ROOT/.env"
STATE_DIR="$ROOT/.autonavlog-worktree"
MARKER="# Generated by AutoNavLog Codex worktree setup"

if [[ -L "$ENV_FILE" || -L "$STATE_DIR" ]]; then
    echo "Refusing cleanup through symlinked worktree configuration." >&2
    exit 1
fi

if [[ ! -f "$ENV_FILE" ]]; then
    exit 0
fi

if ! grep -qxF "$MARKER" "$ENV_FILE"; then
    echo "Refusing cleanup because .env was not generated by the Codex worktree setup." >&2
    exit 1
fi

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

if [[ ! "${COMPOSE_PROJECT_NAME:-}" =~ ^autonavlog-wt-[0-9a-f]{8}$ ]]; then
    echo "Refusing volume cleanup for unexpected project: ${COMPOSE_PROJECT_NAME:-<unset>}" >&2
    exit 1
fi
if [[ ! "${AUTONAVLOG_IMAGE:-}" =~ ^autonavlog:wt-[0-9a-f]{8}$ ]]; then
    echo "Refusing image cleanup for unexpected image: ${AUTONAVLOG_IMAGE:-<unset>}" >&2
    exit 1
fi

EXPECTED_ID="$(python3 -c 'import hashlib, sys; print(hashlib.sha256(sys.argv[1].encode()).hexdigest()[:8])' "$ROOT")"
if [[ "$COMPOSE_PROJECT_NAME" != "autonavlog-wt-$EXPECTED_ID" ||
      "$AUTONAVLOG_IMAGE" != "autonavlog:wt-$EXPECTED_ID" ]]; then
    echo "Refusing cleanup because the generated project/image do not belong to this worktree path." >&2
    exit 1
fi

# Task/process ownership still requires the disposal checks in development_worktrees.md.
# A clean tree alone does not establish that another Codex task has finished.
if ! WORKTREE_STATUS="$(git status --porcelain --untracked-files=all)"; then
    echo "Cannot inspect worktree changes; retaining generated configuration." >&2
    exit 1
fi
if [[ -n "$WORKTREE_STATUS" ]]; then
    echo "Refusing cleanup because the worktree has uncommitted or untracked changes." >&2
    exit 1
fi

if command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; then
    if ! docker compose down -v --remove-orphans; then
        echo "Warning: generated Compose configuration failed; retrying cleanup with the base Compose file." >&2
        if ! COMPOSE_FILE=compose.yaml docker compose -p "$COMPOSE_PROJECT_NAME" down -v --remove-orphans; then
            echo "Cleanup failed; retaining generated configuration for retry." >&2
            exit 1
        fi
    fi
    # Distinguish an already-removed image from a failed removal, without forcing users off it.
    if ! IMAGE_ID="$(docker image ls --quiet --filter "reference=$AUTONAVLOG_IMAGE")"; then
        echo "Cannot inspect the worktree image; retaining generated configuration for retry." >&2
        exit 1
    fi
    if [[ -n "$IMAGE_ID" ]] && ! docker image rm "$AUTONAVLOG_IMAGE"; then
        echo "Worktree image remains; retaining generated configuration for cleanup retry." >&2
        exit 1
    fi
else
    echo "Docker is unavailable; retaining generated configuration for cleanup retry." >&2
    exit 1
fi

rm -rf "$STATE_DIR"
rm -f "$ENV_FILE"
